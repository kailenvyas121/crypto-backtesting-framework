"""
Daily refresh of the local market-data cache, then rewrites the auto-generated
"Market data" section of data_map.md from the cache metadata.

    python scripts/update_market_data.py                 # every cached dataset
    python scripts/update_market_data.py --asset BTC     # one (downloads it if new)
    python scripts/update_market_data.py --asset ETH --start 2020-01-01 --timeframe 1h

This is the ONLY step that should touch the network. Builders and chart scripts read
from disk, so a new bar never changes a final chart until you rebuild on purpose.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.market_data import CACHE, MarketData  # noqa: E402

DATA_MAP = ROOT / "data_map.md"
BEGIN = "<!-- market-data:begin (generated by scripts/update_market_data.py, do not edit by hand) -->"
END = "<!-- market-data:end -->"

CAVEATS = {
    "ccxt": "Exchange-specific series; never spliced with another venue. Daily bars are "
            "00:00-24:00 UTC, stamped with the open time. Closed bars only.",
    "yfinance": "Unofficial Yahoo wrapper. Raw close and adj_close both kept (auto_adjust=False). "
                "Sessions checked against the XNYS calendar. Current constituents only: no "
                "survivorship-bias correction.",
}


def render_data_map() -> None:
    sections = []
    for meta_path in sorted(CACHE.rglob("*.meta.json")):
        m = json.loads(meta_path.read_text())
        name = m["pair"] or m["ticker"]
        source = f"CCXT / {m['exchange'].capitalize()}" if m["provider"] == "ccxt" else "yfinance / Yahoo Finance"
        revisions = sum(len(r["bars"]) for r in m.get("revisions", []))
        sections.append("\n".join([
            f"### {name} {m['timeframe']}",
            "",
            f"- Provider: {source}",
            f"- Range: {m['first_timestamp'][:10]} to {m['last_timestamp'][:10]} ({m['timestamp_convention']})",
            f"- Rows: {m['rows']:,}   Missing bars: {m['missing_bars']}   Validation: {m['validation']}",
            f"- Local file: `{m['local_file']}`",
            f"- Last updated: {m['updated_at']}" + (f"   Provider revisions logged: {revisions}" if revisions else ""),
            f"- Notes: {CAVEATS[m['provider']]}",
        ]))
    block = "\n".join([BEGIN, "## Market data", "", "\n\n".join(sections) or "_nothing cached yet_", END])

    text = DATA_MAP.read_text() if DATA_MAP.exists() else "# Data map\n"
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        text = head + block + rest.split(END, 1)[1]
    else:
        text = text.rstrip() + "\n\n" + block + "\n"
    DATA_MAP.write_text(text)


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--asset", help="symbol, e.g. BTC, BTC/USD, SPY. Omit to update everything cached.")
    p.add_argument("--timeframe", default="1d")
    p.add_argument("--start", default=None, help="only used when --asset is not cached yet")
    args = p.parse_args()

    data = MarketData()
    if args.asset:
        try:
            data.update(args.asset, args.timeframe)
        except FileNotFoundError:
            data.get(args.asset, start=args.start, timeframe=args.timeframe)
    else:
        data.update_all()
    render_data_map()
    print(f"data_map.md market-data section refreshed")


if __name__ == "__main__":
    main()
